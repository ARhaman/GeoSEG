"""The three augmentation arms of Experiment A.

Arm 1 "none"      -- identity. The honest floor.
Arm 2 "classical" -- horizontal flip, small elastic/affine warp, amplitude
                     scaling, Gaussian noise. NOTE: no vertical flip and no
                     90-degree rotation. Seismic sections have a physical
                     up-direction (younger strata above older); flipping them
                     vertically teaches the network geologically impossible
                     stratigraphy. Papers that use generic torchvision
                     augmentation on seismic routinely make this mistake.
Arm 3 "pix2pix"   -- real patches PLUS synthetic (mask -> seismic) patches
                     generated by a Pix2Pix trained on the same label budget.
                     Critical: the generator only ever sees the labelled
                     patches available at that budget, otherwise the arm leaks
                     information from data the baseline never had.
"""
from __future__ import annotations

import numpy as np


class NoAug:
    def __call__(self, x, y):
        return x, y


class ClassicalAug:
    def __init__(self, seed=0, p_flip=0.5, p_noise=0.5, p_gain=0.5, p_shift=0.3):
        self.rng = np.random.default_rng(seed)
        self.p_flip, self.p_noise = p_flip, p_noise
        self.p_gain, self.p_shift = p_gain, p_shift

    def __call__(self, x, y):
        # lateral flip only -- preserves stratigraphic polarity
        if self.rng.random() < self.p_flip:
            x, y = x[::-1].copy(), y[::-1].copy()
        # amplitude gain (models acquisition/processing gain differences)
        if self.rng.random() < self.p_gain:
            x = x * self.rng.uniform(0.85, 1.15)
        # additive band-limited noise
        if self.rng.random() < self.p_noise:
            n = self.rng.normal(0, self.rng.uniform(0.01, 0.08), x.shape)
            x = x + n.astype(x.dtype)
        # small vertical (depth) shift, wrap-free, mimics static shift
        if self.rng.random() < self.p_shift:
            s = int(self.rng.integers(-6, 7))
            if s:
                x = np.roll(x, s, axis=1)
                y = np.roll(y, s, axis=1)
                if s > 0:
                    x[:, :s], y[:, :s] = x[:, s:s + 1], y[:, s:s + 1]
                else:
                    x[:, s:], y[:, s:] = x[:, s - 1:s], y[:, s - 1:s]
        return x.astype(np.float32), y


def build_augment(arm: str, seed: int = 0):
    if arm == "none":
        return NoAug()
    if arm in ("classical", "pix2pix", "ldm", "l1only"):
        # generative arms still use classical aug on top -- otherwise the
        # comparison conflates "synthetic data" with "any augmentation at all"
        return ClassicalAug(seed=seed)
    raise ValueError(f"unknown augmentation arm {arm!r}")


def load_synthetic(path, max_n=None):
    """Load a .npz written by scripts/03_train_pix2pix.py -> (X, Y)."""
    d = np.load(path)
    X, Y = d["X"], d["Y"]
    if max_n is not None:
        X, Y = X[:max_n], Y[:max_n]
    return X.astype(np.float32), Y.astype(np.int64)
